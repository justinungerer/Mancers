"""Stage the 26 vendored filmcraft crates as `reel-*` crates in C:\\Users\\ELMYZ\\rr-vendor-reel.

Only src/ and build scripts are kept (tests, examples and benches of a dependency are never built
here). Every 'filmcraft'/'FilmCraft' becomes 'reel'/'Reel'. The upstream licence files are copied
next to the crates.
"""

import re
import shutil
from pathlib import Path

STAGE = Path(r"C:\Users\ELMYZ\rr-vendor-stage")
OUT = Path(r"C:\Users\ELMYZ\rr-vendor-reel")
CHECKOUT = Path(r"C:\Users\ELMYZ\.cargo\git\checkouts\filmcraft-58288263de9b27d9\2c5ba7a")
TEXT = {".rs", ".toml", ".md", ".txt", ".json", ".wgsl", ".glsl", ".ron", ".csv", ".yml", ".yaml"}

REPL = [
    (re.compile(r"FILMCRAFT"), "REEL"),
    (re.compile(r"FilmCraft"), "Reel"),
    (re.compile(r"Filmcraft"), "Reel"),
    (re.compile(r"filmcraft"), "reel"),
]


def scrub(text: str) -> str:
    for pat, new in REPL:
        text = pat.sub(new, text)
    return text


def strip_manifest(text: str) -> str:
    # Drop sections a path dependency never uses: dev-deps, examples, tests, benches.
    out, skip = [], False
    for line in text.splitlines():
        if line.startswith("["):
            skip = bool(re.match(r"\[(\[)?(dev-dependencies|example|test|bench)", line))
        if not skip:
            out.append(line)
    return "\n".join(out) + "\n"


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    for d in sorted(STAGE.glob("filmcraft-*")):
        short = d.name.removeprefix("filmcraft-")
        dest = OUT / short
        dest.mkdir()
        for item in d.iterdir():
            if item.name in {"tests", "examples", "benches", ".cargo-checksum.json", "Cargo.toml.orig", ".cargo_vcs_info.json"}:
                continue
            if item.is_dir():
                shutil.copytree(item, dest / item.name)
            else:
                shutil.copy2(item, dest / item.name)
        for f in dest.rglob("*"):
            if f.is_file() and (f.suffix.lower() in TEXT or f.name == "Cargo.toml"):
                t = f.read_text(encoding="utf-8")
                if f.name == "Cargo.toml":
                    t = strip_manifest(t)
                    t = re.sub(r"^# THIS FILE IS AUTOMATICALLY GENERATED BY CARGO.*?\n\n", "", t, flags=re.S)
                f.write_text(scrub(t), encoding="utf-8", newline="\n")
        for f in sorted(dest.rglob("*")):
            if "filmcraft" in f.name.lower():
                f.rename(f.with_name(scrub(f.name)))
    for lic in ("LICENSE-MIT", "LICENSE-APACHE"):
        src = CHECKOUT / lic
        if src.exists():
            shutil.copy2(src, OUT / lic)
    (OUT / "README.md").write_text(
        "# Vendored media crates (`reel-*`)\n\n"
        "Pure-Rust codec and container crates used by RenderRoulette, vendored into this repository and "
        "renamed. Only the library sources are kept. Licensed MIT OR Apache-2.0; see LICENSE-MIT and "
        "LICENSE-APACHE in this folder.\n",
        encoding="utf-8", newline="\n")
    print("staged", len(list(OUT.iterdir())), "entries in", OUT)


if __name__ == "__main__":
    main()
